import React, { useRef, useMemo, useEffect } from 'react';
import * as THREE from 'three';
import { useFrame } from '@react-three/fiber';
import { useGLTF } from '@react-three/drei';
import { useShowroom } from '../../context/ShowroomContext';

export function Wardrobe({ position = [4.4, 0, -1.2], rotation = [0, 0, 0] }) {
  const groupRef = useRef();
  const {
    selectedProductId,
    hoveredProductId,
    setHoveredProductId,
    focusProduct,
    colorVariants,
  } = useShowroom();

  const isSelected = selectedProductId === 'wardrobe';
  const isHovered = hoveredProductId === 'wardrobe';
  const selectedColor = colorVariants.wardrobe ? colorVariants.wardrobe.hex : '#5c3e21';

  // Load actual ready-made Poly Haven 3D Cabinet model with PBR wood textures
  const { scene } = useGLTF('/models/modern_wooden_cabinet/modern_wooden_cabinet.gltf');
  const model = useMemo(() => scene.clone(true), [scene]);

  useEffect(() => {
    model.traverse((child) => {
      if (child.isMesh) {
        child.castShadow = true;
        child.receiveShadow = true;
        if (child.material) {
          child.material = child.material.clone();
          child.material.color.set(selectedColor);
          child.material.needsUpdate = true;
        }
      }
    });
  }, [model, selectedColor]);

  useFrame((state, delta) => {
    if (groupRef.current && (isSelected || isHovered)) {
      groupRef.current.position.y = THREE.MathUtils.lerp(groupRef.current.position.y, 0.04, delta * 6);
    } else if (groupRef.current) {
      groupRef.current.position.y = THREE.MathUtils.lerp(groupRef.current.position.y, 0, delta * 6);
    }
  });

  return (
    <group
      ref={groupRef}
      position={position}
      rotation={rotation}
      onClick={(e) => {
        e.stopPropagation();
        focusProduct('wardrobe');
      }}
      onPointerOver={(e) => {
        e.stopPropagation();
        setHoveredProductId('wardrobe');
        document.body.style.cursor = 'pointer';
      }}
      onPointerOut={(e) => {
        e.stopPropagation();
        setHoveredProductId(null);
        document.body.style.cursor = 'auto';
      }}
    >
      {/* Selection Glow */}
      {isSelected && (
        <mesh position={[0, 0.02, 0]} rotation={[-Math.PI / 2, 0, 0]}>
          <ringGeometry args={[1.2, 1.4, 48]} />
          <meshBasicMaterial color="#dfa04c" transparent opacity={0.65} side={THREE.DoubleSide} />
        </mesh>
      )}

      {/* Realistic 3D Modern Wooden Cabinet / Wardrobe */}
      <primitive
        object={model}
        scale={[1.05, 1.05, 1.05]}
        position={[0, 0, 0]}
      />
    </group>
  );
}

useGLTF.preload('/models/modern_wooden_cabinet/modern_wooden_cabinet.gltf');
